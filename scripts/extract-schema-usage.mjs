/**
 * Extracts every (table, column) pair the app touches, and writes a SQL file
 * that reports which of them do not exist in the live database.
 *
 * v2 was written from migration files rather than against the live schema, so
 * a column can be wrong in a way nothing catches: TypeScript is happy, the
 * build passes, and the failure only appears when a real person hits the
 * endpoint. That is how `mental_profiles.onboarding_completed` blocked every
 * signup. This turns that whole class of bug into one query.
 *
 *   node scripts/extract-schema-usage.mjs > scripts/check-schema-usage.sql
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory()
      ? walk(full)
      : /\.tsx?$/.test(name)
        ? [full]
        : [];
  });
}

/** Returns the source slice from `start` to its matching closing brace. */
function balanced(source, start) {
  let depth = 0;
  for (let i = start; i < source.length; i += 1) {
    if (source[i] === "{") depth += 1;
    else if (source[i] === "}") {
      depth -= 1;
      if (depth === 0) return source.slice(start, i + 1);
    }
  }
  return "";
}

const pairs = new Set();

for (const file of walk("src")) {
  const source = readFileSync(file, "utf8");

  // .from("table") … .select("a, b, c")
  const selects = source.matchAll(
    /\.from\(\s*"([a-z_]+)"\s*\)([\s\S]{0,600}?)\.select\(\s*(?:\n\s*)?"([^"]+)"/g,
  );
  for (const [, table, , columns] of selects) {
    for (const raw of columns.split(",")) {
      const column = raw.trim().split(/[\s(:]/)[0];
      if (/^[a-z_]+$/.test(column) && column !== "count") pairs.add(`${table}|${column}`);
    }
  }

  // .from("table").insert({ … }) and .upsert({ … })
  const writes = source.matchAll(/\.from\(\s*"([a-z_]+)"\s*\)\s*\.(?:insert|upsert|update)\(\s*/g);
  for (const match of writes) {
    const braceAt = source.indexOf("{", match.index + match[0].length - 1);
    if (braceAt === -1) continue;
    const body = balanced(source, braceAt);
    // Top-level `key:` only — nested objects are JSON payloads, not columns.
    let depth = 0;
    for (let i = 0; i < body.length; i += 1) {
      const char = body[i];
      if (char === "{" || char === "[") depth += 1;
      else if (char === "}" || char === "]") depth -= 1;
      else if (depth === 1) {
        const rest = body.slice(i);
        const key = /^([a-z_]+)\s*:/.exec(rest);
        if (key && (i === 0 || /[{,\s]/.test(body[i - 1]))) pairs.add(`${match[1]}|${key[1]}`);
      }
    }
  }
}

const rows = [...pairs]
  .sort()
  .map((p) => {
    const [table, column] = p.split("|");
    return `  ('${table}','${column}')`;
  })
  .join(",\n");

process.stdout.write(`-- Generated by scripts/extract-schema-usage.mjs — read-only.
-- Every (table, column) the app reads or writes. Anything listed in the
-- result does NOT exist in the live database and will fail at runtime.

with used(t, c) as (values
${rows}
)
select u.t as table_name, u.c as missing_column
from used u
left join information_schema.columns i
  on i.table_schema = 'public' and i.table_name = u.t and i.column_name = u.c
left join information_schema.tables x
  on x.table_schema = 'public' and x.table_name = u.t
where i.column_name is null and x.table_name is not null
order by 1, 2;
`);
